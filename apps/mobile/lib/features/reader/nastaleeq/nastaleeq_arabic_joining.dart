const List<_CodeRange> _kJoinCausingRanges = [
  (0x0640, 0x0640),
  (0x0883, 0x0885),
];

bool _within(List<_CodeRange> ranges, int code) =>
    ranges.any((range) => code >= range.$1 && code <= range.$2);

bool isArabicMark(int code) =>
    code == _kGraphemeJoiner || _within(_kMarkRanges, code);

bool isArabicLetter(int code) => _within(_kLetterRanges, code);

ArabicJoining arabicJoiningOf(int code) {
  if (_within(_kDualJoiningRanges, code)) return ArabicJoining.dual;
  if (_within(_kRightJoiningRanges, code)) return ArabicJoining.right;
  if (_within(_kJoinCausingRanges, code)) return ArabicJoining.causing;
  return ArabicJoining.none;
}

bool arabicJoinsToNext(int code) => switch (arabicJoiningOf(code)) {
  ArabicJoining.dual || ArabicJoining.causing => true,
  ArabicJoining.right || ArabicJoining.none => false,
};

bool arabicJoinsToPrevious(int code) => switch (arabicJoiningOf(code)) {
  ArabicJoining.dual || ArabicJoining.right || ArabicJoining.causing => true,
  ArabicJoining.none => false,
};
